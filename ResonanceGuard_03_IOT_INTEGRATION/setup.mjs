import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { randomBytes } from 'node:crypto';
import { parseEnv } from 'node:util';
import { fileURLToPath } from 'node:url';

process.chdir(fileURLToPath(new URL('.', import.meta.url)));

if (!existsSync('.env'))
{
    const prefix = `rg-demo/${randomBytes(8).toString('hex')}/rg01`;
    writeFileSync('.env', `MQTT_URL=mqtt://broker.hivemq.com:1883\nMQTT_PREFIX=${prefix}\nPORT=3000\n`);
}
const env = parseEnv(readFileSync('.env', 'utf8'));
let url;
try
{
    url = new URL(env.MQTT_URL);
}
catch
{
    throw new Error('Invalid MQTT_URL in .env (value hidden).');
}
const prefix = env.MQTT_PREFIX;
if (!prefix || prefix.includes('CHANGE_THIS') || !/^rg-demo\/[A-Za-z0-9_/-]+\/rg01$/.test(prefix) ||
    prefix.length > 160 || url.protocol !== 'mqtt:' || url.username || url.password ||
    (url.pathname && url.pathname !== '/') || url.search || url.hash ||
    (env.PORT && (!/^\d+$/.test(env.PORT) || Number(env.PORT) < 1 || Number(env.PORT) > 65535)))
{
    throw new Error('Invalid demo .env: use mqtt:// without credentials/path and a unique rg-demo/.../rg01 prefix; check PORT. Existing files preserved.');
}
writeFileSync('firmware/config.h', `#pragma once\n// Generated by npm run setup. Copy this file to Wokwi too.\nconst char *BROKER = ${JSON.stringify(url.hostname)};\nconst char *PREFIX = ${JSON.stringify(prefix)};\nconstexpr int BROKER_PORT = ${Number(url.port || 1883)};\n`);
console.log('Ready. Copy firmware/config.h to Wokwi along with the other firmware files.');
