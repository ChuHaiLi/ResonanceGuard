import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { randomBytes } from 'node:crypto';

if (!existsSync('.env'))
{
    const prefix = `rg-demo/${randomBytes(8).toString('hex')}/rg01`;
    writeFileSync('.env', `MQTT_URL=mqtt://test.mosquitto.org:1883\nMQTT_PREFIX=${prefix}\nPORT=3000\n`);
}
const text = readFileSync('.env', 'utf8');
const get = name => text.split(/\r?\n/).find(line => line.startsWith(`${name}=`))?.slice(name.length + 1).trim();
const url = new URL(get('MQTT_URL'));
const prefix = get('MQTT_PREFIX');
if (!prefix || prefix.includes('CHANGE_THIS') || /[+#]/.test(prefix) || url.protocol !== 'mqtt:')
{
    throw new Error('Invalid demo .env: requires mqtt:// and a unique MQTT_PREFIX');
}
writeFileSync('firmware/config.h', `#pragma once\n// Generated by npm run setup. Copy this file to Wokwi too.\nconst char *BROKER = ${JSON.stringify(url.hostname)};\nconst char *PREFIX = ${JSON.stringify(prefix)};\nconstexpr int BROKER_PORT = ${Number(url.port || 1883)};\n`);
console.log('Ready. Copy firmware/config.h to Wokwi along with the other firmware files.');
console.log(`MQTT prefix: ${prefix}`);
